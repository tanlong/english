export const roleNpcs = roleCharacters.map(([topicId, role, id, name, kind]) => {
  const topic = curriculum.find((entry) => entry.topicId === topicId)!;
  return {
    id,
    name,
    kind,
    role,
    sceneId: topic.sceneId,
    color: topic.color,
    topics: [topicId],
    greeting:
      role === "guide"
        ? `Hi, I'm ${name}! Let's learn some useful English before you practise.`
        : `Hi, I'm ${name}! Let's practise together. I can help when you need a hint.`,
    description:
      role === "guide"
        ? `Giáo viên chủ đề ${topic.shortLabel}: học từ vựng, xem câu mẫu và hỏi cách dùng.`
        : `Luyện ${topic.shortLabel} có hướng dẫn: trò chuyện, nhận gợi ý và xem cách diễn đạt tự nhiên.`,
  };
});
